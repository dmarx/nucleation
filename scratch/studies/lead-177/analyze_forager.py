"""Summarize results/forager.jsonl into results/forager_summary.md."""
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import forager as F  # noqa: E402

rows = [json.loads(l) for l in (HERE / "results" / "forager.jsonl").read_text().splitlines()]
by = defaultdict(list)
for r in rows:
    by[(r["scenario"], r["arm"])].append(r)
oracle = {(r["scenario"], r["seed"]): r["post_intake"] for r in rows if r["arm"] == "oracle"}


def paired_wins(sc, a, b):
    """Seeds where arm a's post-change intake beats arm b's, out of n."""
    A = {r["seed"]: r["post_intake"] for r in by[(sc, a)]}
    B = {r["seed"]: r["post_intake"] for r in by[(sc, b)]}
    s = sorted(A)
    return sum(A[k] > B[k] for k in s), len(s)


lines = ["# Forager study summary (CASE-239), generated by analyze_forager.py", "",
         f"{len(rows)} runs; {len({r['seed'] for r in rows})} seeds per cell; "
         f"change at t = {F.World().t_change}, run length {F.World().T}.", "",
         "| scenario | arm | survived | median death (steps after change) | post-change net intake, mean | regret vs oracle, mean | missed failures | false warnings | first correct warning, median steps (n) | probes after change | attended features at end (modal) |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
for sc in F.SCENARIOS:
    for a in F.ARMS:
        rs = by[(sc, a)]
        if not rs:
            continue
        n = len(rs)
        surv = sum(r["survived"] for r in rs)
        deaths = [r["died"] - F.World().t_change for r in rs if r["died"] is not None]
        intake = np.mean([r["post_intake"] for r in rs])
        regret = np.mean([oracle[(sc, r["seed"])] - r["post_intake"] for r in rs])
        fw = [r["first_warn"] for r in rs if r["first_warn"] is not None]
        att = Counter(tuple(r["attended_end"]) for r in rs).most_common(1)[0]
        lines.append(
            f"| {sc} | {a} | {surv}/{n} | {int(np.median(deaths)) if deaths else '-'} | "
            f"{intake:.0f} | {regret:.0f} | {np.mean([r['missed'] for r in rs]):.1f} | "
            f"{np.mean([r['false_warn'] for r in rs]):.1f} | "
            f"{(str(int(np.median(fw))) + ' (' + str(len(fw)) + ')') if fw else '-'} | "
            f"{np.mean([r['probes_post'] for r in rs]):.1f} | {list(att[0])} ({att[1]}/{n}) |")
lines += ["", "## Paired comparisons (post-change net intake, same seeds)", ""]
for sc in F.SCENARIOS:
    for rule in ("rls", "tab"):
        w, n = paired_wins(sc, f"learner-{rule}", f"frozen-{rule}")
        sl = sum(r["survived"] for r in by[(sc, f"learner-{rule}")])
        sf = sum(r["survived"] for r in by[(sc, f"frozen-{rule}")])
        lines.append(f"- {sc}, {rule}: learner beats frozen criterion in {w}/{n} seeds; "
                     f"survival {sl}/{n} against {sf}/{n}.")
    w, n = paired_wins(sc, "learner-rls", "score-rls")
    lines.append(f"- {sc}: energy-target learner beats score-target learner in {w}/{n} seeds; "
                 f"survival {sum(r['survived'] for r in by[(sc, 'learner-rls')])}/{n} against "
                 f"{sum(r['survived'] for r in by[(sc, 'score-rls')])}/{n}.")
lines += ["", "## Features added after the change, by the learners", ""]
for sc in F.SCENARIOS:
    for a in ("learner-rls", "learner-tab", "frozen-rls", "frozen-tab", "featfrozen-rls", "featfrozen-tab", "score-rls", "arbitrary-rls"):
        rs = by[(sc, a)]
        post = Counter(f for r in rs for (t, f) in r["added"] if t >= F.World().t_change)
        lines.append(f"- {sc}, {a}: features added after the change, runs counted per feature: "
                     f"{dict(sorted(post.items())) or 'none'}")
(HERE / "results" / "forager_summary.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
