"""Summarise results_e1.jsonl and results_e2.jsonl into summary.md (rerun after run.py)."""
import json
import os
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PATHS = ["none/linear", "wm/linear", "am/linear", "swm/linear", "fullgroup/linear",
         "none/bezier", "am/bezier", "swm/bezier", "none/polychain", "am/polychain"]


def load(name):
    p = os.path.join(HERE, name)
    if not os.path.exists(p):
        return []
    with open(p) as f:
        return [json.loads(l) for l in f if l.strip()]


def fmt(v):
    return "–" if v is None else f"{v:.3f}"


def mean(xs):
    xs = [x for x in xs if x is not None]
    return float(np.mean(xs)) if xs else None


def table(rows, group_keys, metric, out, extra):
    groups = defaultdict(list)
    for r in rows:
        groups[tuple(r[k] for k in group_keys)].append(r)
    cols = [p for p in PATHS if any(p in r["paths"] for r in rows)]
    out.append("| " + " | ".join(group_keys + ["n"] + [e[0] for e in extra] + cols) + " |")
    out.append("|" + "---|" * (len(group_keys) + 1 + len(extra) + len(cols)))
    for g in sorted(groups, key=lambda g: tuple(str(x).zfill(4) for x in g)):
        rs = groups[g]
        cells = [str(x) for x in g] + [str(len(rs))]
        cells += [fmt(mean([e[1](r) for r in rs])) for e in extra]
        cells += [fmt(mean([r["paths"][c][metric] for r in rs if c in r["paths"]])) for c in cols]
        out.append("| " + " | ".join(cells) + " |")
    out.append("")


def main():
    out = ["# LEAD-157 summary (generated by summarize.py)", ""]
    e1 = load("results_e1.jsonl")
    extra1 = [("relyA_a", lambda r: r["reliance"][0]["acc_A_only"]),
              ("relyB_a", lambda r: r["reliance"][0]["acc_B_only"]),
              ("relyA_b", lambda r: r["reliance"][1]["acc_A_only"]),
              ("relyB_b", lambda r: r["reliance"][1]["acc_B_only"]),
              ("err_a", lambda r: r["end_test"][0][1]), ("err_b", lambda r: r["end_test"][1][1]),
              ("fcorr_am_L1", lambda r: r["feature_corr_am"][0]),
              ("fcorr_am_L2", lambda r: r["feature_corr_am"][1]),
              ("llfc_am_L2", lambda r: r["paths"]["am/linear"]["llfc_cos"][1])]
    for metric in ("test_loss_barrier", "test_err_barrier"):
        out += [f"## e1: mechanism pairs, mean {metric} (both-cue test set)", ""]
        table(e1, ["cond", "width"], metric, out, extra1 if metric == "test_loss_barrier" else [])
    e2 = load("results_e2.jsonl")
    extra2 = [("lam_max", lambda r: float(np.mean(r["lam_max"]))),
              ("train_err", lambda r: float(np.mean([e[1] for e in r["end_train"]]))),
              ("test_err", lambda r: float(np.mean([e[1] for e in r["end_test"]]))),
              ("fcorr_am_L2", lambda r: r["feature_corr_am"][1])]
    for metric in ("train_err_barrier", "train_loss_barrier"):
        out += [f"## e2: load x temperature grid, mean {metric} (both-cue train set)", ""]
        table(e2, ["temp", "width"], metric, out, extra2 if metric == "train_err_barrier" else [])
    # per-pair maxima: does any alignment fail to remove the barrier between same-mechanism pairs?
    out += ["## e1: per-pair best aligned linear test loss barrier (min over wm, am, swm, fullgroup)", ""]
    out.append("| cond | width | per-pair values |")
    out.append("|---|---|---|")
    g = defaultdict(list)
    for r in e1:
        v = min(r["paths"][k]["test_loss_barrier"] for k in
                ("wm/linear", "am/linear", "swm/linear", "fullgroup/linear") if k in r["paths"])
        g[(r["cond"], r["width"])].append(round(v, 3))
    for k in sorted(g, key=lambda k: (k[0], k[1])):
        out.append(f"| {k[0]} | {k[1]} | {g[k]} |")
    with open(os.path.join(HERE, "summary.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
