"""Run the alarm-world rungs (R0-R3) over faults and seeds, one JSON line per
run (resumable), then write results/ladder_summary.md.
Usage: python3 -I study_ladder.py [n_seeds]
"""
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import ladder as L  # noqa: E402

OUT = HERE / "results" / "ladder.jsonl"


def jsonable(v):
    if hasattr(v, "item"):
        return v.item()
    if isinstance(v, (list, tuple)):
        return [jsonable(u) for u in v]
    return v


def main(n):
    OUT.parent.mkdir(exist_ok=True)
    done = set()
    if OUT.exists():
        done = {(r["rung"], r["fault"], r["seed"]) for r in map(json.loads, OUT.read_text().splitlines())}
    with OUT.open("a") as fh:
        for fault in L.FAULTS:
            for rung in L.RUNGS:
                for seed in range(n):
                    if (rung, fault, seed) in done:
                        continue
                    r = L.run(rung, fault, seed)
                    fh.write(json.dumps({k: jsonable(v) for k, v in r.items()}) + "\n")
                    fh.flush()


def summarize():
    rows = [json.loads(l) for l in OUT.read_text().splitlines()]
    by = defaultdict(list)
    for r in rows:
        by[(r["fault"], r["rung"])].append(r)
    mi = sorted({round(r["mi_pre"], 6) for r in rows})
    out = ["# Alarm-world rungs (R0-R3), generated by study_ladder.py", "",
           f"{len(rows)} runs, {len({r['seed'] for r in rows})} seeds per cell. "
           "All four rungs read the same passive sensor channel: within each seed "
           "and fault, I(reading; smoke) before the fault is identical across rungs (checked below).", "",
           "| fault | rung | fires put out after the fault | of them in heat | valve open without fire, mean steps | faults registered (runs) | registrations per run, mean | named by the probes (modal) | steps from fault to first naming, median | added test condition |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for fault in L.FAULTS:
        for rung in L.RUNGS:
            rs = by[(fault, rung)]
            fa = sum(r["fires_after"] for r in rs)
            po = sum(r["put_out_after"] for r in rs)
            hf = sum(r["hot_fires_after"] for r in rs)
            hp = sum(r["hot_put_out"] for r in rs)
            reg = sum(r["registrations"] > 0 for r in rs)
            loc = Counter(r["located"][0] for r in rs if r["located"])
            lt = [r["located_t"] for r in rs if r["located_t"] is not None]
            cond = Counter(c for r in rs for c in r["added_condition"])
            out.append(f"| {fault} | {rung} | {po}/{fa} | {hp}/{hf} | "
                       f"{np.mean([r['valve_open_no_fire'] for r in rs]):.0f} | {reg}/{len(rs)} | "
                       f"{np.mean([r['registrations'] for r in rs]):.2f} | "
                       f"{(loc.most_common(1)[0][0] + ' ' + str(loc.most_common(1)[0][1]) + '/' + str(len(rs))) if loc else '-'} | "
                       f"{int(np.median(lt)) if lt else '-'} | {dict(cond) or '-'} |")
    # identical correlations check
    same = all(len({round(r["mi_pre"], 12) for r in rows if r["seed"] == s and r["fault"] == f}) == 1
               for s in {r["seed"] for r in rows} for f in L.FAULTS)
    out += ["", f"Identical I(reading; smoke) across rungs within every seed and fault: {same}. "
            f"Range over seeds, before the fault: {min(mi):.4f} to {max(mi):.4f} bits. "
            "After a fault the rungs that repair restore the correlation and the others do not, "
            "so the post-fault values differ by rung (mean I after the fault, sensor fault: "
            + ", ".join(f"{g} {np.mean([r['mi_post'] for r in by[('sensor', g)]]):.4f}" for g in L.RUNGS) + ")."]
    (HERE / "results" / "ladder_summary.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 100)
    summarize()
