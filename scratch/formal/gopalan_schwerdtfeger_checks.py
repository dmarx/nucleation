# Lemma 3.7: phi_n path of length > 2^(n/2)
def phi(n):
    # returns predicate on assignments of length n
    if n == 2:
        return lambda x: (not x[0]) or x[1]
    prev = phi(n - 2)
    def f(x):
        if not prev(x[:n - 2]): return False
        a, b = x[n - 2], x[n - 1]
        if a == 1 and b == 0: return False   # clause (not x_{n-1} or x_n), read as excluding 10
        if a == 0 and b == 1:
            t = tuple([0] * (n - 4) + [1, 1]) if n >= 4 else ()
            return tuple(x[:n - 2]) == t
        return True
    return f
for n in [2, 4, 6, 8, 10, 12]:
    f = phi(n)
    S = {x for x in product((0, 1), repeat=n) if f(x)}
    comps = components(S)
    # check path: connected, all degrees <=2, two of degree 1
    deg = {x: sum(1 for i in range(n) if x[:i] + (1 - x[i],) + x[i+1:] in S) for x in S}
    ispath = len(comps) == 1 and max(deg.values()) <= 2 and sum(1 for d in deg.values() if d == 1) == 2
    print(f'Lemma 3.7 n={n}: |S|={len(S)}, path={ispath}, length={len(S)-1}, 2^(n/2)={2**(n//2)}')

