from itertools import product, combinations, permutations
from collections import deque

def bits(s): return tuple(int(c) for c in s)

def components(R):
    R = set(R); comps = []; seen = set()
    for r in R:
        if r in seen: continue
        q = deque([r]); comp = {r}; seen.add(r)
        while q:
            u = q.popleft()
            for i in range(len(u)):
                v = u[:i] + (1 - u[i],) + u[i+1:]
                if v in R and v not in seen:
                    seen.add(v); comp.add(v); q.append(v)
        comps.append(comp)
    return comps

def closed(R, op, k):
    R = set(R)
    for ts in product(R, repeat=k):
        if tuple(op(*col) for col in zip(*ts)) not in R: return False
    return True

maj = lambda a, b, c: int(a + b + c >= 2)
AND = lambda a, b: a & b
OR = lambda a, b: a | b
MINO = lambda a, b, c: a ^ b ^ c

def bijunctive(R): return closed(R, maj, 3) if R else True
def cw_bij(R): return all(bijunctive(c) for c in components(R))

OR2 = {(0, 1), (1, 0), (1, 1)}; NAND2 = {(0, 0), (0, 1), (1, 0)}
def substitutions(R, n):
    """all binary relations obtained by fixing n-2 coords to constants (vars once)"""
    out = []
    for i, j in permutations(range(n), 2):
        rest = [k for k in range(n) if k not in (i, j)]
        for c in product((0, 1), repeat=len(rest)):
            S = {(t[i], t[j]) for t in R if all(t[k] == v for k, v in zip(rest, c))}
            out.append(S)
    return out
def or_free(R, n): return all(S != OR2 for S in substitutions(R, n))
def nand_free(R, n): return all(S != NAND2 for S in substitutions(R, n))

def identifications(R, n):
    """all relations obtained by identification of variables (maps of positions onto m<=n vars)"""
    out = []
    for m in range(1, n + 1):
        for f in product(range(m), repeat=n):
            if set(f) != set(range(m)): continue
            S = set()
            for x in product((0, 1), repeat=m):
                t = tuple(x[f[k]] for k in range(n))
                if t in R: S.add(x)
            out.append((m, S))
    return out

def tight_props(R, n):
    return dict(cwbij=cw_bij(R), orfree=or_free(R, n), nandfree=nand_free(R, n))
def safe_props(R, n):
    ids = identifications(R, n)
    return dict(cwbij=all(cw_bij(S) for m, S in ids),
                orfree=all(or_free(S, m) if m >= 2 else True for m, S in ids),
                nandfree=all(nand_free(S, m) if m >= 2 else True for m, S in ids))

