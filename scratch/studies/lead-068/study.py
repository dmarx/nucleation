"""Run LEAD-068's study (CASE-285's simulation arm). Writes results.json and results.md."""
from __future__ import annotations

import json
import sys
import time
from dataclasses import asdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from model import Params, run, summarize, timing_prediction  # noqa: E402

SEEDS = list(range(20))
SLOW, FAST = 1.0, 10.0
HERE = Path(__file__).resolve().parent

VARIANTS = ([("none", {})]
            + [("limits", dict(q=q, fp=fp)) for fp in (0.02, 0.10, 0.30) for q in (0.25, 0.5, 0.75, 0.9, 1.0)]
            + [("suspend", dict(h=h, fa=fa)) for fa in (0.05, 0.20, 0.50) for h in (0.5, 0.8, 0.95, 1.0)]
            + [("pause", dict(pause=P)) for P in (0.5, 1, 2, 4, 8, 16, 27)])

ROBUST = [("none", {}), ("det_mean=0.5", dict(det_mean=0.5)), ("det_mean=5", dict(det_mean=5.0)),
          ("reviewers=2", dict(reviewers=2)), ("reviewers=8", dict(reviewers=8)),
          ("eval_mean=0.5", dict(eval_mean=0.5)), ("t_irr_shape=1", dict(t_irr_shape=1.0)),
          ("t_irr_shape=16", dict(t_irr_shape=16.0)), ("lag=1", dict(lag=1.0)), ("p_obj=0.3", dict(p_obj=0.3))]


def cell(summary, key, fmt="{:.3f}"):
    m, sd = summary[key]["mean"], summary[key]["sd"]
    if sd != sd:  # nan
        return fmt.format(m)
    return (fmt + " ± " + fmt).format(m, sd)


def relative(rows_v, rows_slow, rows_fast):
    """Per seed (common seeds, so in the latency reading the arms share draws):
    share of the slow-fast intervention gap restored, and share of the fast
    arm's benefit gain kept."""
    out = []
    for v, s, f in zip(rows_v, rows_slow, rows_fast):
        gap = s["intervention_capacity"] - f["intervention_capacity"]
        gain = f["benefit_per_benign"] - s["benefit_per_benign"]
        out.append({
            "restored": (v["intervention_capacity"] - f["intervention_capacity"]) / gap,
            "benefit_kept": (v["benefit_per_benign"] - s["benefit_per_benign"]) / gain,
        })
    return summarize(out)


def main():
    t0 = time.time()
    res = {"seeds": SEEDS, "slow": SLOW, "fast": FAST, "base": asdict(Params())}
    md = ["# LEAD-068 results", "",
          f"Seeds: {len(SEEDS)} per configuration; cells are mean ± sd across seeds. "
          "Generated by study.py; do not edit by hand.", ""]

    # A. speed sweep, both readings of speed
    res["sweep"] = {}
    md += ["## A. Speed sweep, oversight fixed", "",
           "| reading | s | timing condition at the means | intervention capacity | objectionable detected before irreversible | objectionable irreversible per 1000 actions | benefit per benign action | reviewer load |",
           "|---|---|---|---|---|---|---|---|"]
    for reading in ("latency", "throughput"):
        res["sweep"][reading] = []
        for s in (1, 1.5, 2, 3, 5, 7, 10, 15, 20, 30):
            p = Params(speed=s, reading=reading)
            summ, _ = run(p, SEEDS)
            summ["timing_condition_met"] = timing_prediction(p)
            res["sweep"][reading].append(summ)
            md.append(f"| {reading} | {s:g} | {'met' if summ['timing_condition_met'] else 'not met'} | "
                      f"{cell(summ, 'intervention_capacity')} | {cell(summ, 'detected_before_irreversible_obj')} | "
                      f"{cell(summ, 'obj_irreversible_per_1000', '{:.1f}')} | {cell(summ, 'benefit_per_benign')} | "
                      f"{cell(summ, 'reviewer_utilization', '{:.2f}')} |")
    md.append("")

    # B, C. variants in the fast arm, each reading
    res["variants"] = {}
    for reading, letter in (("latency", "B"), ("throughput", "C")):
        base_slow, rows_slow = run(Params(speed=SLOW, reading=reading), SEEDS)
        base_fast, rows_fast = run(Params(speed=FAST, reading=reading), SEEDS)
        res["variants"][reading] = {"slow": base_slow, "fast": base_fast, "rows": []}
        md += [f"## {letter}. Fast arm (s = {FAST:g}), {reading} reading, variants added in turn", "",
               f"Slow arm: intervention capacity {cell(base_slow, 'intervention_capacity')}, benefit {cell(base_slow, 'benefit_per_benign')}. "
               f"Fast arm: intervention capacity {cell(base_fast, 'intervention_capacity')}, benefit {cell(base_fast, 'benefit_per_benign')}.", "",
               "| variant | settings | intervention capacity | gap restored | benefit kept | benign mean delay (days) | benign share held | benign still held at end | reviewer load | reviews per interception |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        for v, kw in VARIANTS:
            p = Params(speed=FAST, reading=reading, variant=v, **kw)
            summ, rows = run(p, SEEDS)
            rel = relative(rows, rows_slow, rows_fast)
            res["variants"][reading]["rows"].append({"variant": v, "settings": kw, **summ, "relative": rel})
            md.append(f"| {v} | {', '.join(f'{k}={x:g}' for k, x in kw.items()) or '-'} | {cell(summ, 'intervention_capacity')} | "
                      f"{cell(rel, 'restored', '{:.2f}')} | {cell(rel, 'benefit_kept', '{:.2f}')} | {cell(summ, 'benign_mean_delay', '{:.2f}')} | "
                      f"{cell(summ, 'benign_share_held')} | {cell(summ, 'benign_unfinished_held')} | {cell(summ, 'reviewer_utilization', '{:.2f}')} | "
                      f"{cell(summ, 'reviews_per_interception', '{:.1f}')} |")
        md.append("")

    # D. robustness of the slow/fast contrast to the fixed oversight settings
    md += ["## D. Slow against fast arm (latency reading) under other fixed settings", "",
           "| changed setting | slow: intervention capacity | fast: intervention capacity | slow: benefit | fast: benefit |",
           "|---|---|---|---|---|"]
    res["robustness"] = []
    for label, kw in ROBUST:
        a, _ = run(Params(speed=SLOW, **kw), SEEDS)
        b, _ = run(Params(speed=FAST, **kw), SEEDS)
        res["robustness"].append({"changed": label, "slow": a, "fast": b})
        md.append(f"| {label} | {cell(a, 'intervention_capacity')} | {cell(b, 'intervention_capacity')} | "
                  f"{cell(a, 'benefit_per_benign')} | {cell(b, 'benefit_per_benign')} |")
    md.append("")
    md.append(f"Run time: {time.time() - t0:.0f} s.")
    (HERE / "results.json").write_text(json.dumps(res, indent=1))
    (HERE / "results.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
