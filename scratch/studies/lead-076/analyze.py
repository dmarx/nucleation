"""Summarize results/*.jsonl into results/summary.md (LEAD-076).

    python3 -I analyze.py
"""
import json
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")

COLS = [("recognized", "recognized", 2), ("exited", "exited", 2),
        ("median_recognition", "med. recog.", 0), ("median_exit", "med. exit", 0),
        ("outlasts", "outlasts", 2), ("needless_cost", "needless cost", 0),
        ("inspections", "inspections", 0), ("g_end", "g end", 2), ("b_end", "b end", 2),
        ("harm3", "harm, phase 3", 3)]


def load(name):
    p = os.path.join(RES, name)
    if not os.path.exists(p):
        return []
    with open(p) as f:
        return [json.loads(line) for line in f if line.strip()]


def table(rows, extra=()):
    cols = COLS + list(extra)
    out = ["| condition | " + " | ".join(c[1] for c in cols) + " |",
           "|---|" + "---|" * len(cols)]
    for r in rows:
        out.append(f"| {r['key']} | " + " | ".join(f"{r[c[0]]:.{c[2]}f}" for c in cols) + " |")
    return "\n".join(out)


def regime(r):
    if r["exited"] >= 0.9 and r["median_exit"] <= 60:
        return "E"   # evidence-tracking
    if r["exited"] >= 0.5:
        return "R"   # revisable, slowly
    if r["recognized"] >= 0.9:
        return "I"   # inertial: belief corrected, protection persists
    return "S"       # self-confirming: evidence kept from correcting the belief


def phase_tables(rows):
    by = defaultdict(dict)
    kappas, etas = set(), set()
    for r in rows:
        by[r["cell"]][(r["kappa"], r["eta"])] = r
        kappas.add(r["kappa"]); etas.add(r["eta"])
    kappas, etas = sorted(kappas), sorted(etas)
    out = []
    for cell, d in by.items():
        out.append(f"\n**{cell}** (rows kappa, columns eta; regime / share exited / harm in phase 3)\n")
        out.append("| kappa | " + " | ".join(f"eta={e}" for e in etas) + " |")
        out.append("|---|" + "---|" * len(etas))
        for k in kappas:
            cells = []
            for e in etas:
                r = d.get((k, e))
                cells.append("" if r is None else f"{regime(r)} {r['exited']:.2f} {r['harm3']:.3f}")
            out.append(f"| {k} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def main():
    parts = ["# LEAD-076 results summary (generated by analyze.py)\n"]
    parts.append("Safe phase = the 400 steps after the switch (interventions: from the intervention). "
                 "Exit and recognition in steps, censored at the end of the phase. "
                 "'outlasts' = share of seeds whose belief is below the posture threshold "
                 "while P(protect) is still at least 0.5 over the last 20 safe steps. "
                 "1000 seeds per condition, common random numbers.\n")
    parts.append("## First experiment\n")
    parts.append(table(load("first_experiment.jsonl")))
    parts.append("\n## Factorial (feedback | evidence | correction), with habit rows\n")
    parts.append(table(load("factorial.jsonl")))
    parts.append("\n## Interaction contrasts (mean, 95% paired bootstrap interval)\n")
    for r in load("interactions.jsonl"):
        parts.append(f"- {r['key']}: " + "; ".join(
            f"{k} {v[0]:.1f} [{v[1]:.1f}, {v[2]:.1f}]" for k, v in r.items() if k != "key"))
    parts.append("\n## Interventions at 50 steps after the switch (CLAIM-446's four)\n")
    parts.append(table(load("interventions.jsonl"),
                       extra=[("b_after_30", "b +30", 2), ("pp_after_30", "P(protect) +30", 2)]))
    parts.append("\n## Sensitivity\n")
    parts.append(table(load("sensitivity.jsonl")))
    parts.append("\n## Phase diagrams\n")
    parts.append("E evidence-tracking (90% exit, median within 60 steps); R revisable (half exit); "
                 "I inertial (belief corrected in 90%, protection persists); S self-confirming.")
    parts.append(phase_tables(load("phase_diagram.jsonl")))
    with open(os.path.join(RES, "summary.md"), "w") as f:
        f.write("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
