"""Summarise results/*.jsonl into results/summary.md and results/summary.json.

    python3 -I analyze.py
"""
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
LOG2 = np.log(2.0)
B_D = 0.5            # b^(-d) per step, b = sqrt 2, d = 2
THRESH = 2 ** -0.5   # a direction "does not decay" if its factor exceeds this
NS = [10, 100, 1000, 10 ** 4, 10 ** 5, 10 ** 6]


def load(name):
    p = os.path.join(RES, name)
    if not os.path.exists(p):
        return []
    return [json.loads(line) for line in open(p) if line.strip()]


def resolved(lam, err):
    lam, err = np.asarray(lam), np.asarray(err)
    return (lam > 3 * err) & (lam > 0)


def decay_fit(rec, kfrom=1):
    """Per-step factor of each rank's eigenvalue: slope of log lambda over the
    levels from kfrom to the last level at which that rank is resolved."""
    levels = sorted(int(k) for k in rec["levels"])
    P = len(rec["levels"]["0"]["lam"])
    out = []
    for j in range(P):
        ks, ys, ws = [], [], []
        for k in levels:
            if k < kfrom:
                continue
            d = rec["levels"][str(k)]
            lam, err = d["lam"][j], d["err"][j]
            if lam > 3 * err and lam > 0:
                ks.append(k)
                ys.append(np.log(lam))
                ws.append(lam / err)
            else:
                break
        if len(ks) >= 3:
            ks, ys, ws = map(np.asarray, (ks, ys, ws))
            A = np.vstack([ks, np.ones_like(ks)]).T
            W = np.diag(ws ** 2)
            cov = np.linalg.inv(A.T @ W @ A)
            beta = cov @ A.T @ W @ ys
            # scale the error by the fit's own scatter when it exceeds the weights'
            resid = ys - A @ beta
            chi2 = float(resid @ W @ resid) / max(len(ks) - 2, 1)
            se = np.sqrt(cov[0, 0] * max(chi2, 1.0))
            late = float(np.exp((ys[-1] - ys[-3]) / (ks[-1] - ks[-3])))
            out.append({"rank": j + 1, "factor": float(np.exp(beta[0])), "late": late,
                        "factor_lo": float(np.exp(beta[0] - 2 * se)),
                        "factor_hi": float(np.exp(beta[0] + 2 * se)),
                        "levels": [int(ks[0]), int(ks[-1])]})
        else:
            out.append({"rank": j + 1, "factor": None, "levels": [int(k) for k in ks]})
    return out


def stiff_counts(rec):
    res = {}
    for k, d in rec["levels"].items():
        lam, err = np.asarray(d["lam"]), np.asarray(d["err"])
        ok = resolved(lam, err)
        res[k] = {"counts": [int(((n * lam >= 1) & ok).sum()) for n in NS],
                  "unresolved": int((~ok).sum()),
                  # an unresolved eigenvalue is below 3 sigma: count it as
                  # "maybe" for n with n * 3 sigma >= 1
                  "upper": [int(((n * np.maximum(lam, 3 * err) >= 1)).sum()) for n in NS]}
    return res


def field_overlap(vec):
    v = np.asarray(vec)
    return float(abs(v[0]))


def nn_overlap(vec):
    v = np.asarray(vec)
    return float(abs(v[1] + v[2]) / np.sqrt(2))


def main():
    mc = load("fisher_clusters.jsonl")
    strip = load("strip.jsonl")
    burn = load("burn_check.jsonl")
    summary = {"fisher": {}, "clusters": {}, "strip": {}, "burn": {}}
    md = ["# LEAD-208 results summary", "",
          "Generated by analyze.py from results/*.jsonl.", ""]

    # ---------------- Fisher spectra
    md += ["## Decimated Fisher spectra", "",
           "Eigenvalues of g^k = Cov(E[Phi | o_k]) per configuration, 13 parameters "
           "(field + 12 two-spin couplings), b = sqrt 2 per level. Errors are "
           "jackknife over 16 blocks of whole chains. `*` marks an eigenvalue "
           "below 3 sigma (unresolved).", ""]
    for rec in sorted(mc, key=lambda r: (r["L"], r["T_over_Tc"])):
        key = rec["key"]
        levels = sorted(int(k) for k in rec["levels"])
        md += ["### %s (L = %d, T/T_c = %.1f, %d configurations, %.0f s)" %
               (key, rec["L"], rec["T_over_Tc"], rec["nconf"], rec["seconds"]), ""]
        md.append("| k | " + " | ".join("l%d" % (j + 1) for j in range(13)) + " | field ovl v1 | NN ovl v1, v2 |")
        md.append("|" + "---|" * 16)
        for k in levels:
            d = rec["levels"][str(k)]
            cells = []
            for lam, err in zip(d["lam"], d["err"]):
                cells.append(("%.3g" % lam) + ("" if (lam > 3 * err and lam > 0) else "*"))
            v = d["vec_top3"]
            md.append("| %d | %s | %.2f | %.2f, %.2f |" % (
                k, " | ".join(cells), field_overlap(v[0]), nn_overlap(v[0]), nn_overlap(v[1])))
        fits = decay_fit(rec)
        nrel = sum(1 for f in fits if f["factor"] is not None and f["factor_lo"] > THRESH)
        nrel_point = sum(1 for f in fits if f["factor"] is not None and f["factor"] > THRESH)
        md += ["", "Per-step decay factors (fit over levels 1.., resolved only; 2-sigma range):", ""]
        md.append("| rank | factor | range | levels | last two steps |")
        md.append("|---|---|---|---|---|")
        for f in fits:
            if f["factor"] is None:
                md.append("| %d | - | - | %s |" % (f["rank"], f["levels"]))
            else:
                md.append("| %d | %.3f | %.3f-%.3f | %d-%d | %.3f |" % (
                    f["rank"], f["factor"], f["factor_lo"], f["factor_hi"], *f["levels"], f["late"]))
        sc = stiff_counts(rec)
        md += ["", "Relevant count (factor's 2-sigma range above 2^-1/2): **%d** "
               "(point estimate above: %d)." % (nrel, nrel_point), "",
               "Stiff count, n * lambda >= 1 among resolved eigenvalues, n = "
               + ", ".join("%g" % n for n in NS) + " (upper bound counting unresolved at 3 sigma):", ""]
        md.append("| k | counts | upper |")
        md.append("|---|---|---|")
        for k in levels:
            c = sc[str(k)]
            md.append("| %d | %s | %s |" % (k, c["counts"], c["upper"]))
        md.append("")
        summary["fisher"][key] = {"decay": fits, "relevant_count": nrel,
                                  "relevant_count_point": nrel_point,
                                  "stiff_counts": sc}

    # ---------------- clusters
    md += ["## Largest geometric spin cluster", "",
           "Box counting on the torus (aligned grid), mean log N(eps) over "
           "configurations; slope fitted over eps = 2..L/4. Mass scaling "
           "from the mean mass at L = 16, 32, 64. Exact D at T_c: 187/96 = 1.948.", ""]
    md.append("| key | eps | local slopes | fit slope (2..L/4) | mean mass |")
    md.append("|---|---|---|---|---|")
    bytemp = {}
    for rec in sorted(mc, key=lambda r: (r["T_over_Tc"], r["L"])):
        c = rec["clusters"]
        eps = np.asarray(c["eps"], float)
        y = np.asarray(c["mean_logN"])
        local = -np.diff(y) / np.diff(np.log(eps))
        sel = (eps >= 2) & (eps <= rec["L"] / 4)
        slope = -np.polyfit(np.log(eps[sel]), y[sel], 1)[0]
        md.append("| %s | %s | %s | %.3f | %.1f +- %.1f |" % (
            rec["key"], c["eps"], ", ".join("%.3f" % x for x in local), slope,
            c["mean_mass"], c["sem_mass"]))
        summary["clusters"][rec["key"]] = {"box_slope": float(slope),
                                           "local": local.tolist(),
                                           "mass": c["mean_mass"]}
        bytemp.setdefault(rec["T_over_Tc"], []).append((rec["L"], c["mean_mass"]))
    md.append("")
    for t, pts in sorted(bytemp.items()):
        if len(pts) >= 2:
            Ls, ms = map(np.asarray, zip(*sorted(pts)))
            D = np.polyfit(np.log(Ls), np.log(ms), 1)[0]
            loc = np.diff(np.log(ms)) / np.diff(np.log(Ls))
            md.append("- T/T_c = %.1f: mass-scaling D over L = %s: %.3f (local %s)" % (
                t, Ls.tolist(), D, ", ".join("%.3f" % x for x in loc)))
            summary["clusters"]["mass_D_%.1f" % t] = float(D)
    md.append("")

    # ---------------- strip
    md += ["## Predictive information on a width-W strip (exact)", "",
           "Column blocks: I(c_t; c_t+1) in bits, equal to the block quantity "
           "2H(T) - H(2T) at every T because the column process is Markov.", ""]
    for r in strip:
        if r["key"].startswith("colmi"):
            I = np.asarray(r["I_bits"])
            W = np.asarray(r["W"], float)
            dI = np.diff(I)
            # fit I = a W + b + c ln W over W >= 6
            sel = W >= 6
            A = np.vstack([W[sel], np.ones(sel.sum()), np.log(W[sel])]).T
            coef = np.linalg.lstsq(A, I[sel], rcond=None)[0]
            md.append("- T/T_c = %.1f: I = %s; increments %s; fit W >= 6: "
                      "a = %.4f bits per site, b = %.3f, c = %.3f bits per ln W" % (
                          r["T_over_Tc"], ", ".join("%.4f" % x for x in I),
                          ", ".join("%.4f" % x for x in dI), *coef))
            summary["strip"][r["key"]] = {"I": I.tolist(), "fit_a_b_c": coef.tolist()}
    md += ["", "One row: I_pred(T) = 2H(T) - H(2T) in bits for the spins of a "
           "single row, exact (hidden Markov over columns).", ""]
    md.append("| key | T = 1.. | I_pred(T) | last increment |")
    md.append("|---|---|---|---|")
    sat = {}
    for r in strip:
        if r["key"].startswith("row"):
            I = np.asarray(r["I_bits"])
            md.append("| %s | 1..%d | %s | %.2g |" % (
                r["key"], len(I), ", ".join("%.4f" % x for x in I), I[-1] - I[-2]))
            summary["strip"][r["key"]] = I.tolist()
            d = sat.setdefault(r["T_over_Tc"], {})
            if r["W"] not in d or len(I) > d[r["W"]][0]:
                d[r["W"]] = (len(I), I[-1])
    md.append("")
    for t, d in sorted(sat.items()):
        Ws, Is = map(np.asarray, zip(*sorted((w, v[1]) for w, v in d.items())))
        sl = np.diff(Is) / np.diff(np.log(Ws))
        md.append("- T/T_c = %.1f: largest-T value against W = %s: %s; d I / d ln W = %s bits; "
                  "Bialek-style K = 2 dI/d ln W in nats = %s" % (
                      t, Ws.tolist(), ", ".join("%.4f" % x for x in Is),
                      ", ".join("%.3f" % x for x in sl),
                      ", ".join("%.3f" % (2 * x * LOG2) for x in sl)))
    md.append("")

    # ---------------- burn check
    if burn:
        md += ["## Compatible-chain burn-in check (L = 32, T_c, same seed)", ""]
        md.append("| level | burn 1: top 6 | burn 8: top 6 |")
        md.append("|---|---|---|")
        b1 = next(r for r in burn if r["burn"] == 1)
        b8 = next(r for r in burn if r["burn"] == 8)
        for k in sorted(b1["levels"], key=int):
            f = lambda r: ", ".join("%.3g" % x for x in r["levels"][k]["lam"][:6])
            md.append("| %s | %s | %s |" % (k, f(b1), f(b8)))
        md.append("")

    with open(os.path.join(RES, "summary.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    with open(os.path.join(RES, "summary.json"), "w") as fh:
        json.dump(summary, fh, indent=1)
    print("\n".join(md))


if __name__ == "__main__":
    main()
