"""Summarise results.jsonl: for each model, width and normalization, the
smallest coupling at which the whole wins under exclusion, and a table of
verdicts at matched couplings. Writes summary.md.

    python3 -I summarise.py
"""
import json
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
rows = [json.loads(l) for l in open(os.path.join(HERE, "results.jsonl"))]

by = defaultdict(list)
for r in rows:
    by[(r["normalize"], r["model"], r["width"])].append(r)

WHOLE = {"mind": "mind", "group": "group"}
out = ["# LEAD-063 summary (generated by summarise.py)", ""]
out.append("## Threshold: smallest coupling at which the whole is the complex")
out.append("")
out.append("| MIB | model | links between parts | first coupling where whole wins | "
           "whole wins at every larger stable coupling? | largest stable coupling |")
out.append("|---|---|---:|---:|---|---:|")
for (norm, model, width), rs in sorted(by.items(), key=lambda kv: (not kv[0][0], kv[0][1] != "mind", kv[0][2])):
    rs = sorted(rs, key=lambda r: r["coupling"])
    ok = [r for r in rs if "winner" in r]
    wins = [r["coupling"] for r in ok if r["winner"] == WHOLE[model]]
    first = min(wins) if wins else None
    after = [r for r in ok if first is not None and r["coupling"] >= first]
    mono = all(r["winner"] == WHOLE[model] for r in after) if wins else False
    out.append(f"| {'size-normalized' if norm else 'unnormalized'} | {model} | {width} | "
               f"{first if first is not None else 'none'} | {'yes' if mono else 'no'} | "
               f"{max(r['coupling'] for r in ok)} |")
out.append("")
out.append("## Verdicts at matched coupling (size-normalized MIB)")
out.append("")
out.append("Coupling x between parts (modules of the mind; members of the group), "
           "links between each pair of parts = width. Phi in nats per step; "
           "winner under exclusion.")
out.append("")
out.append("| coupling | width | mind: Phi module / mind -> winner | "
           "group: Phi module / member / group -> winner |")
out.append("|---:|---:|---|---|")
idx = {(r["normalize"], r["model"], r["width"], r["coupling"]): r for r in rows}
for x in [0.0, 0.05, 0.1, 0.15, 0.2, 0.25]:
    for width in [1, 2, 3]:
        m = idx.get((True, "mind", width, x))
        g = idx.get((True, "group", width, x))
        def fmt(r, levels):
            if r is None:
                return "not run"
            if "error" in r:
                return "unstable"
            return " / ".join(f"{r['phi'][k]:.4f}" for k in levels) + f" -> {r['winner']}"
        out.append(f"| {x} | {width} | {fmt(m, ['module', 'mind'])} | "
                   f"{fmt(g, ['module', 'member', 'group'])} |")
open(os.path.join(HERE, "summary.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
