"""Run the sensor-network arms over seeds, one JSON line per run (resumable),
then write results/network_summary.md.
Usage: python3 -I study_network.py [n_seeds]
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import network as N  # noqa: E402

OUT = HERE / "results" / "network.jsonl"
# arm name -> (network arm, keyword overrides); the last rows vary a setting
CELLS = {
    "fixed": ("fixed", {}),
    "self": ("self", {}),
    "self-eta0.005": ("self", {"eta": 0.005}),
    "anchored": ("anchored", {}),
    "anchored-K50": ("anchored", {"K": 50}),
    "anchored-K200": ("anchored", {"K": 200}),
    "writable": ("writable", {}),
    "admitted": ("admitted", {}),
    "admitted-thr1.0": ("admitted", {"admit_thr": 1.0}),
}


def main(n):
    OUT.parent.mkdir(exist_ok=True)
    done = set()
    if OUT.exists():
        done = {(r["cell"], r["seed"]) for r in map(json.loads, OUT.read_text().splitlines())}
    with OUT.open("a") as fh:
        for cell, (arm, kw) in CELLS.items():
            for seed in range(n):
                if (cell, seed) in done:
                    continue
                r = N.run(arm, seed, **kw)
                r["cell"] = cell
                fh.write(json.dumps(r) + "\n")
                fh.flush()


def summarize():
    rows = [json.loads(l) for l in OUT.read_text().splitlines()]
    by = defaultdict(list)
    for r in rows:
        by[r["cell"]].append(r)
    fixed = {r["seed"]: r["err_late"] for r in by["fixed"]}
    out = ["# Sensor network revising its correspondences, generated by study_network.py", "",
           f"{len(rows)} runs, {len(by['fixed'])} seeds per cell. Errors are |zhat - z| on the "
           "target's true positions, which no arm sees; 'late' is the last 1,000 of 3,000 steps "
           "(the jump is at step 500).", "",
           "| cell | error before the jump | radius before | error late | radius late | late error below fixed's (seeds) | calibration events admitted / offered |",
           "|---|---|---|---|---|---|---|"]
    for cell in CELLS:
        rs = by[cell]
        m = lambda k: np.mean([r[k] for r in rs])
        below = sum(r["err_late"] < fixed[r["seed"]] for r in rs)
        out.append(f"| {cell} | {m('err_pre'):.3f} | {m('rad_pre'):.3f} | {m('err_late'):.3f} | "
                   f"{m('rad_late'):.3f} | {below}/{len(rs)} | "
                   f"{m('admitted'):.0f} / {m('offered'):.0f} |")
    (HERE / "results" / "network_summary.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 40)
    summarize()
