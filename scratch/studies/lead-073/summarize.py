"""Write results/summary.md from the JSON outputs of measure.py."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")


def load(name):
    p = os.path.join(RES, name)
    return json.load(open(p)) if os.path.exists(p) else None


def fmt(x):
    return f"{x:.3g}"


def model_block(name, r, sweep):
    L = [f"## {name}", "",
         f"- d = {r['d']}, vocabulary {r['V']}; {r['n_context_vectors']} context vectors "
         f"({r['n_random_vectors']} from random token strings, {r['n_sampled_vectors']} from the model's own samples, "
         f"the rest from the relation prompts).",
         f"- Final layer norm: Σ β_i/γ_i = {fmt(r['ln_offset_sum_beta_over_gamma'])} (nonzero, so the exact span F is all of ℝ^d); "
         f"largest residual of the hyperplane identity mean((f − β)/γ) = 0: {fmt(r['ln_hyperplane_residual'])}.",
         "- Singular values of the context matrix relative to the largest, at ranks 1, 2, 3, 11, 51, 101 and last: "
         + ", ".join(fmt(r["sv_F_rel"][i]) for i in [0, 1, 2, 10, 50, 100, len(r["sv_F_rel"]) - 1]) + ".",
         "- Of the centred unembedding matrix, same ranks: "
         + ", ".join(fmt(r["sv_G_rel"][i]) for i in [0, 1, 2, 10, 50, 100, len(r["sv_G_rel"]) - 1]) + ".",
         "", "### Spans at the pre-registered tolerances", "",
         "| rtol | dim F | dim G | dim M = dim N | dim F (random only) | dim F (samples only) |",
         "|---|---|---|---|---|---|"]
    for k, s in r["spans"].items():
        L.append(f"| {k} | {s['dim_F']} | {s['dim_G']} | {s['dim_M']} | {s['dim_F_random_only']} | {s['dim_F_sampled_only']} |")
    L += ["", "### Relations", "",
          "| relation | subjects | replies | LOO R² | model acc. among replies | probe agrees with model (LOO) | chance | Γ_q energy in nearly logit-invisible F |",
          "|---|---|---|---|---|---|---|---|"]
    for n, x in r["relations"].items():
        if "skipped" in x:
            L.append(f"| {n} | {x['n_subjects']} | skipped: {x['skipped']} | | | | | |")
            continue
        L.append(f"| {n} | {x['n_subjects']} | {x['n_replies']} | {fmt(x['loo_r2'])} | {fmt(x['model_acc_among_replies'])} | "
                 f"{fmt(x['probe_faithfulness_loo'])} | {fmt(x['chance'])} | {fmt(x['Gamma_q_energy_in_low_visibility_F'])} |")
    L += ["", "Containment, worst direction's squared share outside (pass ≤ 0.01):", "",
          "| relation | rtol | Γ ⊆ N | Γ_q ⊆ M | max angle Γ_q vs M (°) | pass |", "|---|---|---|---|---|---|"]
    for n, x in r["relations"].items():
        for k, t in x.get("tests", {}).items():
            L.append(f"| {n} | {k} | {fmt(t['Gamma_in_N']['worst_out'])} | {fmt(t['Gamma_q_in_M']['worst_out'])} | "
                     f"{fmt(t['Gamma_q_in_M']['max_angle_deg'])} | {'yes' if t['pass'] else 'no'} |")
    if sweep:
        L += ["", "### Post-hoc tolerance sweep (not pre-registered)", "",
              "| rtol | dim F = dim M | " + " | ".join(f"{n}: Γ⊆N / Γ_q⊆M" for n in sweep["relations"] if "tests" in sweep["relations"][n]) + " |",
              "|---|---|" + "---|" * sum("tests" in v for v in sweep["relations"].values())]
        for k, s in sweep["spans"].items():
            cells = []
            for n, x in sweep["relations"].items():
                if "tests" in x:
                    t = x["tests"][k]
                    cells.append(f"{fmt(t['Gamma_in_N']['worst_out'])} / {fmt(t['Gamma_q_in_M']['worst_out'])}")
            L.append(f"| {k} | {s['dim_M']} | " + " | ".join(cells) + " |")
    return L + [""]


def main():
    out = ["# LEAD-073 results", "", "Generated by summarize.py from results/*.json.", ""]
    for name, base in [("GPT-2 small", "gpt2"), ("Pythia-70m", "pythia-70m")]:
        r = load(base + ".json")
        if r:
            out += model_block(name, r, load(base + "_sweep.json"))
    open(os.path.join(RES, "summary.md"), "w").write("\n".join(out))


if __name__ == "__main__":
    main()
