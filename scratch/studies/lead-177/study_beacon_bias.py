"""scratch/studies/lead-177/study_beacon_bias.py

The arm LEAD-177's network study did not run: a beacon the revision can
neither rewrite nor refuse, but which is itself miscalibrated. And the
remedy it suggests: a rarer, separately protected survey that revises the
beacon's calibration on a slower scale (an anchor for the anchor). Filed
2026-11-23 from the owner's proposal that self-correction depends on how
evidence, evaluation and authority are coupled, and on what the system is
prevented from rewriting or rejecting.

Usage: python3 -I study_beacon_bias.py [n_seeds]
Writes results/beacon_bias.jsonl and results/beacon_bias_summary.md.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import network as N

DELTA = (0.3, -0.2)
CELLS = {
    "anchored": dict(),
    "anchored-miscalibrated": dict(beacon_bias=DELTA),
    "anchored-miscalibrated-surveyed": dict(beacon_bias=DELTA, survey_every=100),
    "anchored-miscalibrated-surveyed-rare": dict(beacon_bias=DELTA, survey_every=500),
}


def main(n=40):
    here = os.path.dirname(os.path.abspath(__file__))
    rows = []
    for cell, kw in CELLS.items():
        for seed in range(n):
            r = N.run("anchored", seed, **kw); r["cell"] = cell; rows.append(r)
    with open(os.path.join(here, "results", "beacon_bias.jsonl"), "w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    lines = ["# A protected but miscalibrated beacon, generated by study_beacon_bias.py", "",
             f"{len(rows)} runs, {n} seeds per cell. Beacon miscalibration delta = {DELTA}, "
             f"|delta| = {np.hypot(*DELTA):.3f}. Errors are |zhat - z| on true positions; "
             "'late' is the last 1,000 of 3,000 steps.", "",
             "| cell | error late (mean) | min | max | radius late |", "|---|---|---|---|---|"]
    for cell in CELLS:
        e = [r["err_late"] for r in rows if r["cell"] == cell]
        rd = [r["rad_late"] for r in rows if r["cell"] == cell]
        lines.append(f"| {cell} | {np.mean(e):.3f} | {min(e):.3f} | {max(e):.3f} | {np.mean(rd):.3f} |")
    with open(os.path.join(here, "results", "beacon_bias_summary.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 40)
