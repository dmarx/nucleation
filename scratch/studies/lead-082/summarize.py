"""Summarize results.jsonl into results.md: per width and arm, mean (sd)
over seeds of the measures CASE-275 names, plus the recovery tests.

Usage: python3 -I summarize.py [results.jsonl] [results.md]
"""
import json
import os
import sys
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
srcs = sys.argv[1].split(",") if len(sys.argv) > 1 else [
    os.path.join(HERE, f) for f in ("results.jsonl", "results_width.jsonl")
    if os.path.exists(os.path.join(HERE, f))]
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "results.md")
rows = [json.loads(line) for src in srcs for line in open(src)]
ARMS = ["base", "ordinary", "adversarial", "suppress-200", "suppress-1000",
        "suppress-5000", "suppress-5000-wd", "control-A"]

TABLES = [
    ("Expression (behaviour)", [
        ("A_ord", "A on ordinary"),
        ("B_trig_seen", "B, trigger as fine-tuned"),
        ("B_trig_tok_heldout", "B, held-out trigger tokens"),
        ("B_trig_pos_heldout", "B, held-out trigger slots"),
        ("pB_mean", "mean p(B), all triggers"),
        ("coverage_1000", "coverage of B at N=1000 samples"),
        ("B_rank_mean", "rank of B's answer in logits (0 = top)"),
    ]),
    ("Representation and recruitment", [
        ("probe_frozen_auroc_h1", "trigger probe AUROC h1, frozen base reader"),
        ("probe_frozen_auroc_h2", "trigger probe AUROC h2, frozen base reader"),
        ("probe_refit_auroc_h2", "trigger probe AUROC h2, refit reader"),
        ("recruit_trig_tok_heldout", "held-out triggers' projection on base direction (base = 1)"),
        ("u_own_cos_base", "cosine of own trigger direction with base's"),
    ]),
    ("Transmission", [
        ("S_own_mean", "S = v^T J u at h1, own direction"),
        ("logitdiff_trig", "logit[B] - logit[A] under trigger"),
        ("steer_own_1_B", "B on ordinary inputs, +1 x own direction"),
        ("steer_own_2_B", "B on ordinary inputs, +2 x own direction"),
        ("steer_own_4_B", "B on ordinary inputs, +4 x own direction"),
    ]),
    ("Recovery and elicitation on the 18 held-out symbols", [
        ("recovery_full_peak_heldout", "full retraining lr 1e-3, peak over 300 steps"),
        ("recovery_full-slow_peak_heldout", "full retraining lr 1e-4, peak"),
        ("recovery_gate_peak_heldout", "gate-only retraining (embeddings, layer 1), peak"),
        ("delta_B_heldout_trig", "one vector at h1 fitted on 6 symbols, held-out B"),
        ("delta_B_heldout_ord", "same vector, ordinary contexts, held-out B"),
    ]),
]


def fmt(vals):
    v = np.asarray(vals, float)
    return f"{v.mean():.3f} ({v.std():.3f})" if len(v) > 1 else f"{v.mean():.3f}"


by = defaultdict(list)
for r in rows:
    by[(r["H"], r["arm"])].append(r)
out = ["# LEAD-082 results", "",
       "Generated by summarize.py from results.jsonl and results_width.jsonl. "
       "Mean (sd) over seeds; n = seeds.", ""]
for H in sorted({r["H"] for r in rows}):
    arms = [a for a in ARMS if (H, a) in by]
    out.append(f"## Hidden width {H}")
    out.append("")
    out.append("n per arm: " + ", ".join(f"{a} {len(by[(H, a)])}" for a in arms))
    out.append("")
    for title, keys in TABLES:
        out.append(f"### {title}")
        out.append("")
        out.append("| measure | " + " | ".join(arms) + " |")
        out.append("|---|" + "---:|" * len(arms))
        for k, label in keys:
            out.append(f"| {label} | " + " | ".join(fmt([r[k] for r in by[(H, a)]]) for a in arms) + " |")
        out.append("")
    out.append("### Gate-only recovery curve, held-out B (mean over seeds)")
    out.append("")
    steps = list(by[(H, arms[0])][0]["recovery_gate"].keys())
    out.append("| arm | " + " | ".join(f"step {s}" for s in steps) + " |")
    out.append("|---|" + "---:|" * len(steps))
    for a in arms:
        out.append(f"| {a} | " + " | ".join(
            f"{np.mean([r['recovery_gate'][s]['B_heldout'] for r in by[(H, a)]]):.3f}" for s in steps) + " |")
    out.append("")
open(dst, "w").write("\n".join(out))
print("\n".join(out))
